#!/usr/bin/env bash
# Generates the plain Kubernetes manifests in deploy/k8s/ from the Helm chart (DEP-001,
# DEP-007), so both delivery paths cannot drift apart (R-07). Two variants:
#
#   deploy/k8s/tinydb/   TinyDB on a PersistentVolumeClaim, 1 replica, strategy Recreate
#   deploy/k8s/couchdb/  CouchDB StatefulSet + 2 app replicas; needs a pre-created Secret
#
#   deploy/generate-manifests.sh          # write both variants
#   deploy/generate-manifests.sh --check  # fail if the committed manifests are outdated (CI)
set -euo pipefail

cd "$(dirname "$0")"
NAME=cloudinit-nocloud-configurator
CHART="helm/$NAME"
COMMON=(--namespace "$NAME" --set namespace.create=true --set generatedManifests=true)

render_tinydb() {
  echo "# Generated by deploy/generate-manifests.sh from deploy/helm/$NAME - do not edit."
  echo "# Variant TinyDB (DEP-001): TinyDB on a PersistentVolumeClaim, 1 replica, strategy Recreate."
  echo "# Install: kubectl apply -f deploy/k8s/tinydb/"
  helm template "$NAME" "$CHART" "${COMMON[@]}"
}

render_couchdb() {
  echo "# Generated by deploy/generate-manifests.sh from deploy/helm/$NAME - do not edit."
  echo "# Variant CouchDB (DEP-001, DEP-003): single-node CouchDB StatefulSet, 2 app replicas."
  echo "# The credentials are not part of the manifests (DEP-004). Create the Secret first:"
  echo "#"
  echo "#   kubectl create namespace $NAME"
  echo "#   kubectl -n $NAME create secret generic $NAME-couchdb \\"
  echo "#     --from-literal=username=admin \\"
  echo "#     --from-literal=password=\"\$(openssl rand -hex 24)\" \\"
  echo "#     --from-literal=cookieSecret=\"\$(openssl rand -hex 24)\""
  echo "#"
  echo "# Install: kubectl apply -f deploy/k8s/couchdb/"
  helm template "$NAME" "$CHART" "${COMMON[@]}" \
    --set couchdb.enabled=true --set couchdb.existingSecret="$NAME-couchdb" --set replicaCount=2
}

status=0
for variant in tinydb couchdb; do
  out="k8s/$variant/$NAME.yaml"
  if [ "${1:-}" = "--check" ]; then
    if ! diff -u "$out" <("render_$variant"); then
      echo "deploy/$out is outdated: run deploy/generate-manifests.sh and commit the result." >&2
      status=1
    fi
  else
    mkdir -p "k8s/$variant"
    "render_$variant" > "$out"
    echo "Wrote deploy/$out"
  fi
done
[ "${1:-}" = "--check" ] && [ "$status" = 0 ] && echo "deploy/k8s is up to date."
exit "$status"
