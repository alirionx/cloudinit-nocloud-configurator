#!/usr/bin/env bash
# Generates the plain Kubernetes manifests in deploy/k8s/ from the Helm chart with default
# values (DEP-001, DEP-007), so both delivery paths cannot drift apart (R-07).
#
#   deploy/generate-manifests.sh          # write deploy/k8s/cloudinit-nocloud-configurator.yaml
#   deploy/generate-manifests.sh --check  # fail if the committed manifests are outdated (CI)
set -euo pipefail

cd "$(dirname "$0")"
NAME=cloudinit-nocloud-configurator
OUT="k8s/$NAME.yaml"

render() {
  echo "# Generated by deploy/generate-manifests.sh from deploy/helm/$NAME - do not edit."
  echo "# Default setup (DEP-001): TinyDB on a PersistentVolumeClaim, 1 replica, strategy Recreate."
  echo "# Install: kubectl apply -f deploy/k8s/"
  helm template "$NAME" "helm/$NAME" --namespace "$NAME" --set namespace.create=true
}

if [ "${1:-}" = "--check" ]; then
  if ! diff -u "$OUT" <(render); then
    echo "deploy/k8s is outdated: run deploy/generate-manifests.sh and commit the result." >&2
    exit 1
  fi
  echo "deploy/k8s is up to date."
else
  render > "$OUT"
  echo "Wrote deploy/$OUT"
fi
